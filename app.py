import streamlit as st
import pickle

# -----------------------------
# Load the trained model
# -----------------------------
model = pickle.load(open("lungcap-model1.pkl", "rb"))


# -----------------------------
# Page settings
# -----------------------------
st.set_page_config(
    page_title="Lung Capacity Predictor",
    page_icon="🫁",
    layout="wide"
)


# -----------------------------
# Header
# -----------------------------
st.title("🫁 Lung Capacity Predictor")
st.write("Predict lung capacity using a trained Linear Regression model.")

st.divider()


# -----------------------------
# Sidebar
# -----------------------------
st.sidebar.header("Enter Patient Details")

age = st.sidebar.slider(
    "Age",
    min_value=1,
    max_value=100,
    value=18
)

height = st.sidebar.slider(
    "Height",
    min_value=30.0,
    max_value=100.0,
    value=65.0,
    step=0.1
)

smoke = st.sidebar.radio(
    "Does the person smoke?",
    ["No", "Yes"]
)

gender = st.sidebar.radio(
    "Gender",
    ["Female", "Male"]
)

caesarean = st.sidebar.radio(
    "Caesarean birth?",
    ["No", "Yes"]
)


# -----------------------------
# Convert values to numbers
# -----------------------------
if smoke == "Yes":
    smoke_value = 1
else:
    smoke_value = 0

if gender == "Male":
    gender_value = 1
else:
    gender_value = 0

if caesarean == "Yes":
    caesarean_value = 1
else:
    caesarean_value = 0


# -----------------------------
# Main screen
# -----------------------------
col1, col2 = st.columns(2)


with col1:

    st.subheader("👤 Patient Information")

    st.write("**Age:**", age)
    st.write("**Height:**", height)
    st.write("**Smoke:**", smoke)
    st.write("**Gender:**", gender)
    st.write("**Caesarean:**", caesarean)


with col2:

    st.subheader("🤖 Model Information")

    st.write("**Model:** Linear Regression")
    st.write("**Target:** Lung Capacity")
    st.write("**Features:** 5")
    st.write("**Training R²:** 0.861")


st.divider()


# -----------------------------
# Prediction
# -----------------------------
st.subheader("🔮 Prediction")


if st.button(
    "🚀 Predict Lung Capacity",
    use_container_width=True
):

    # Input order must match the training data
    input_data = [[
        age,
        height,
        smoke_value,
        gender_value,
        caesarean_value
    ]]

    prediction = model.predict(input_data)

    result = prediction[0]


    # -----------------------------
    # Display result
    # -----------------------------
    st.success("Prediction completed successfully!")

    result_col1, result_col2, result_col3 = st.columns(3)


    with result_col1:
        st.metric(
            "Predicted Lung Capacity",
            f"{result:.2f}"
        )


    with result_col2:
        st.metric(
            "Age",
            f"{age}"
        )


    with result_col3:
        st.metric(
            "Height",
            f"{height}"
        )


    # Progress bar
    st.write("### Lung Capacity Level")

    # Keep progress between 0 and 100
    progress = min(max(result / 15, 0.0), 1.0)

    st.progress(progress)


    st.info(
        "This prediction is generated by the trained "
        "Linear Regression model."
    )


# -----------------------------
# Footer
# -----------------------------
st.divider()

st.caption(
    "🫁 Lung Capacity Prediction | "
    "Machine Learning Project | Linear Regression"
)

